"""in_gcs integration scenario.

Fluent Bit runs against ``FakeGcsServer`` (src/server/gcs_server.py), which acts
as both the Cloud Storage JSON API (``endpoint``) and the GCE metadata server
(``metadata_server``). The records emitted by in_gcs are captured through an
``http`` output that posts to the suite's shared HTTP server, like the other
input scenarios.

Object bodies are generated by the tests in the default ``out_gcs`` format
(JSON lines with an ISO8601 ``date`` key that has 6 fractional digits).
out_gcs itself cannot be part of the pipeline because its host is hardcoded to
storage.googleapis.com and it cannot be pointed at the fake server.
"""

import functools
import gzip
import json
import os
import re
import time
from datetime import datetime, timezone
from pathlib import Path

import requests

from server.gcs_server import FakeGcsServer
from server.http_server import data_storage, http_server_run
from utils.memory_check import memory_check_enabled
from utils.test_service import FluentBitTestService

# 2023-11-14T22:13:20Z
BASE_EPOCH = 1700000000
GCS_ENV_VARS = (
    "GOOGLE_APPLICATION_CREDENTIALS",
    "GOOGLE_SERVICE_CREDENTIALS",
    "GOOGLE_CLOUD_PROJECT",
    "GCE_METADATA_HOST",
)


def _timeout(seconds):
    return max(seconds * 3, 45) if memory_check_enabled() else seconds


def iso(offset_seconds, micros):
    """Timestamp as written by out_gcs by default."""
    moment = datetime.fromtimestamp(BASE_EPOCH + offset_seconds, tz=timezone.utc)
    return moment.strftime("%Y-%m-%dT%H:%M:%S") + f".{micros:06d}Z"


def jsonl(records, compress=False):
    """Build an object body in the default out_gcs format (json_lines)."""
    body = "".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) + "\n"
                   for r in records).encode("utf-8")
    return gzip.compress(body) if compress else body


def make_records(label, count, first_offset=0):
    """Records of one object: (source body, expected output date)."""
    sources = []
    dates = []
    for index in range(count):
        date = iso(first_offset + index, 123456 + index)
        dates.append(date)
        sources.append({"date": date, "msg": f"{label}-{index}", "n": index})
    return sources, dates


class GcsService:
    def __init__(self, config_file, server=None, wait_for_ready=True):
        self.config_file = os.path.abspath(
            os.path.join(os.path.dirname(__file__), "../config", config_file)
        )
        self.server = server or FakeGcsServer()
        self.extra_env = {}
        self.wait_for_ready = wait_for_ready
        self.service = FluentBitTestService(
            self.config_file,
            data_storage=data_storage,
            data_keys=["payloads", "requests"],
            pre_start=self._start_servers,
            post_stop=self._stop_servers,
        )

    def _start_servers(self, service):
        # Credentials from the host must never reach the plugin: the token has
        # to come from the fake metadata server.
        for name in GCS_ENV_VARS:
            service._set_env(name, "")
            os.environ.pop(name, None)
        for name, value in self.extra_env.items():
            service._set_env(name, value)

        if not self.wait_for_ready:
            # the process may finish before the readiness probe could see it
            service.flb.start = functools.partial(service.flb.start, wait_for_ready=False)

        port = service.allocate_port_env("GCS_PORT")
        self.server.start(port)
        http_server_run(service.test_suite_http_port)
        service.wait_for_http_endpoint(
            f"http://127.0.0.1:{service.test_suite_http_port}/ping",
            timeout=10,
            interval=0.2,
        )

    def _stop_servers(self, service):
        self.server.stop()
        try:
            requests.post(f"http://127.0.0.1:{service.test_suite_http_port}/shutdown",
                          timeout=2)
        except requests.RequestException:
            pass

    def start(self):
        self.service.start()
        self.flb = self.service.flb

    def stop(self):
        self.service.stop()

    def log(self):
        return Path(self.flb.log_file).read_text(encoding="utf-8", errors="replace")

    RESULT_RE = re.compile(r"rehydration (completed with errors|completed|failed):")

    def wait_for_completion(self, timeout=20, expect_failure=False):
        """in_gcs logs 'rehydration completed|failed' once it has nothing left to do.

        A failed run raises immediately with the log tail, unless it is expected."""
        def finished():
            match = self.RESULT_RE.search(self.log())
            if not match:
                return None
            if match.group(1) != "completed" and not expect_failure:
                tail = "\n".join(self.log().splitlines()[-30:])
                raise AssertionError(f"in_gcs run {match.group(1)}:\n{tail}")
            return match.group(1)

        return self.service.wait_for_condition(
            finished,
            timeout=_timeout(timeout),
            interval=0.2,
            description="in_gcs run completion",
        )

    def wait_for_exit(self, timeout=30):
        """Return code of Fluent Bit once it exits by itself (exit_on_complete)."""
        return self.flb.process.wait(timeout=_timeout(timeout))

    def records(self, uri="/data"):
        found = []
        for request in data_storage["requests"]:
            if request["path"] != uri or not isinstance(request["json"], list):
                continue
            found.extend(request["json"])
        return found

    def wait_for_records(self, count, uri="/data", timeout=20):
        return self.service.wait_for_condition(
            lambda: self.records(uri) if len(self.records(uri)) >= count else None,
            timeout=_timeout(timeout),
            interval=0.2,
            description=f"{count} records on {uri}",
        )

    def settle(self, seconds=2.5):
        """Let a couple of flush cycles go by, to assert that nothing else arrives."""
        time.sleep(seconds)


def run(config_file, expected_records, server, *, extra_env=None, uri="/data",
        settle=False):
    """Start Fluent Bit, wait for the run to finish and the records to arrive."""
    service = GcsService(config_file, server)
    service.extra_env = extra_env or {}
    service.start()
    try:
        service.wait_for_completion()
        if expected_records:
            service.wait_for_records(expected_records, uri)
        if settle:
            service.settle()
    except BaseException:
        service.stop()
        raise
    return service


def test_in_gcs_basic_records_and_timestamps():
    server = FakeGcsServer()
    a_src, a_dates = make_records("a", 3, 0)
    b_src, b_dates = make_records("b", 2, 100)
    server.add_object("logs/a.log", jsonl(a_src))
    server.add_object("logs/b.log", jsonl(b_src))

    service = run("in_gcs_basic.yaml", 5, server)
    log = service.log()
    service.stop()

    records = service.records()
    # objects are read in listing order, records of an object in order
    assert [r["msg"] for r in records] == ["a-0", "a-1", "a-2", "b-0", "b-1"]
    assert [r["n"] for r in records] == [0, 1, 2, 0, 1]
    # 'date' is the record timestamp (the output renders it back as ISO8601
    # with microseconds) and it is not duplicated in the body
    assert [r["event_time"] for r in records] == a_dates + b_dates
    # the source 'date' key was consumed as the event time
    assert all(set(r) == {"event_time", "msg", "n"} for r in records)
    assert "rehydration completed: objects processed=2 skipped=0 failed=0" in log
    assert "records emitted=5" in log

    # authentication and request shape
    tokens = server.token_requests()
    assert len(tokens) == 1
    assert tokens[0]["headers"].get("Metadata-Flavor") == "Google"
    assert len(server.list_requests()) == 1
    for request in server.list_requests() + server.object_requests():
        assert request["headers"]["Authorization"] == "Bearer test-token"
        assert request["status"] == 200
    assert {r["name"] for r in server.object_requests()} == {"logs/a.log", "logs/b.log"}
    assert all(r["query"]["alt"] == ["media"] for r in server.object_requests())


def test_in_gcs_pagination():
    server = FakeGcsServer()
    expected = []
    for index in range(3):
        sources, dates = make_records(f"o{index}", 1, index)
        server.add_object(f"page/{index}.log", jsonl(sources))
        expected.append(dates[0])

    service = run("in_gcs_paging.yaml", 3, server)
    service.stop()

    assert [r["event_time"] for r in service.records()] == expected
    listings = server.list_requests()
    assert len(listings) == 3
    assert all(r["query"]["maxResults"] == ["1"] for r in listings)
    assert "pageToken" not in listings[0]["query"]
    assert "pageToken" in listings[1]["query"]
    assert "pageToken" in listings[2]["query"]
    assert listings[1]["query"]["pageToken"] != listings[2]["query"]["pageToken"]


def test_in_gcs_gzip_and_plain_objects():
    server = FakeGcsServer()
    gz_src, gz_dates = make_records("gz", 3, 0)
    plain_src, plain_dates = make_records("plain", 2, 50)
    # compression is 'auto': detected by the gzip header, not by the name
    server.add_object("data/1-compressed.log", jsonl(gz_src, compress=True),
                      content_type="application/gzip")
    server.add_object("data/2-plain.log", jsonl(plain_src))

    service = run("in_gcs_basic.yaml", 5, server)
    service.stop()

    records = service.records()
    assert [r["msg"] for r in records] == ["gz-0", "gz-1", "gz-2", "plain-0", "plain-1"]
    assert [r["event_time"] for r in records] == gz_dates + plain_dates


def test_in_gcs_prefix_and_offsets_are_sent_to_the_api():
    server = FakeGcsServer()
    for name in ("logs/app/a", "logs/app/b", "logs/app/c", "logs/app/d",
                 "logs/app/e", "logs/app/f", "logs/other/x"):
        sources, _ = make_records(name, 1)
        server.add_object(name, jsonl(sources))

    service = run("in_gcs_filter.yaml", 3, server)
    service.stop()

    query = server.list_requests()[0]["query"]
    assert query["prefix"] == ["logs/app/"]
    assert query["startOffset"] == ["logs/app/b"]
    assert query["endOffset"] == ["logs/app/e"]
    assert sorted(r["msg"] for r in service.records()) == [
        "logs/app/b-0", "logs/app/c-0", "logs/app/d-0"]
    assert {r["name"] for r in server.object_requests()} == {
        "logs/app/b", "logs/app/c", "logs/app/d"}


def test_in_gcs_tag_regex_and_object_key():
    server = FakeGcsServer()
    for name in ("fluent-bit-logs/app1/x.log", "fluent-bit-logs/app2/y.log",
                 "fluent-bit-logs/app2/z.log",
                 # no match for the regex: keeps the input tag (gcs.default)
                 "fluent-bit-logs/top.log"):
        sources, _ = make_records(name, 1)
        server.add_object(name, jsonl(sources))

    service = run("in_gcs_tag_regex.yaml", 1, server)
    service.wait_for_records(2, "/solo")
    service.wait_for_records(1, "/shared")
    service.stop()

    app1 = service.records("/data")
    app2 = service.records("/solo")
    assert [r["gcs_object"] for r in app1] == ["fluent-bit-logs/app1/x.log"]
    assert [r["gcs_object"] for r in app2] == ["fluent-bit-logs/app2/y.log",
                                               "fluent-bit-logs/app2/z.log"]
    # only the object that the regex does not match keeps the instance tag
    fallback = service.records("/shared")
    assert [r["gcs_object"] for r in fallback] == ["fluent-bit-logs/top.log"]
    assert all(r["msg"] == r["gcs_object"] + "-0" for r in app1 + app2 + fallback)
    assert "records emitted=4" in service.log()


def test_in_gcs_db_avoids_reingesting_objects(tmp_path):
    db_file = tmp_path / "in_gcs.db"
    server = FakeGcsServer()
    a_src, _ = make_records("a", 2, 0)
    b_src, _ = make_records("b", 1, 10)
    server.add_object("db/a.log", jsonl(a_src), generation=1001)
    server.add_object("db/b.log", jsonl(b_src), generation=2001)
    env = {"GCS_DB_PATH": str(db_file)}

    first = run("in_gcs_db.yaml", 3, server, extra_env=env)
    first.stop()
    assert len(first.records()) == 3
    assert db_file.exists()
    assert len(server.object_requests()) == 2

    # same db: everything was already processed
    second = run("in_gcs_db.yaml", 0, server, extra_env=env, settle=True)
    log = second.log()
    second.stop()
    assert second.records() == []
    assert "objects processed=0 skipped=2" in log
    assert len(server.object_requests()) == 2
    assert len(server.list_requests()) == 2

    # a new generation of an object is a different object
    server.set_generation("db/b.log", 2002)
    third = run("in_gcs_db.yaml", 1, server, extra_env=env)
    log = third.log()
    third.stop()
    assert [r["msg"] for r in third.records()] == ["b-0"]
    assert "objects processed=1 skipped=1" in log
    downloads = server.object_requests("db/b.log")
    assert len(downloads) == 2
    assert downloads[-1]["query"]["generation"] == ["2002"]


def test_in_gcs_missing_object_is_skipped():
    server = FakeGcsServer()
    for name in ("err/a.log", "err/b.log", "err/c.log"):
        sources, _ = make_records(name, 1)
        server.add_object(name, jsonl(sources))
    server.set_object_status("err/b.log", 404)

    service = run("in_gcs_basic.yaml", 2, server)
    log = service.log()
    service.stop()

    assert [r["msg"] for r in service.records()] == ["err/a.log-0", "err/c.log-0"]
    assert "object 'err/b.log' not found" in log
    assert "objects processed=2 skipped=1 failed=0" in log
    # a 404 is final: no retries
    assert len(server.object_requests("err/b.log")) == 1


def test_in_gcs_transient_errors_are_retried_once_ingested():
    server = FakeGcsServer()
    sources, _ = make_records("flaky", 2)
    server.add_object("retry/flaky.log", jsonl(sources))
    server.fail_object("retry/flaky.log", 2, status=500)

    service = run("in_gcs_basic.yaml", 2, server)
    log = service.log()
    service.stop()

    assert [r["msg"] for r in service.records()] == ["flaky-0", "flaky-1"]
    statuses = [r["status"] for r in server.object_requests("retry/flaky.log")]
    assert statuses == [500, 500, 200]
    assert log.count("temporary error") == 2
    assert "objects processed=1 skipped=0 failed=0" in log


def test_in_gcs_unauthorized_refreshes_the_token_once():
    server = FakeGcsServer()
    server.set_tokens(["stale-token", "fresh-token"], accepted={"fresh-token"})
    sources, _ = make_records("auth", 2)
    server.add_object("auth/o.log", jsonl(sources))

    service = run("in_gcs_basic.yaml", 2, server)
    log = service.log()
    service.stop()

    assert [r["msg"] for r in service.records()] == ["auth-0", "auth-1"]
    assert len(server.token_requests()) == 2
    listings = server.list_requests()
    assert [r["status"] for r in listings] == [401, 200]
    assert listings[0]["headers"]["Authorization"] == "Bearer stale-token"
    assert listings[1]["headers"]["Authorization"] == "Bearer fresh-token"
    assert "unauthorized, refreshing the token" in log
    assert len(server.object_requests()) == 1


def test_in_gcs_round_trip_out_gcs_format():
    """Objects written the way out_gcs writes them (json_lines, ISO8601 date
    with microseconds, optional gzip) are read back with the same content and
    timestamps."""
    server = FakeGcsServer()
    originals = []
    for index in range(4):
        originals.append({
            "date": iso(index * 7, 999990 + index),
            "text": f"héllo wörld {index} ☃",
            "count": index * 1000003,
            "ratio": 0.5 + index,
            "ok": index % 2 == 0,
            "nested": {"k": [1, "two", None], "i": {"deep": index}},
            "nothing": None,
        })
    server.add_object("rt/chunk-1.json.gz", jsonl(originals[:2], compress=True))
    server.add_object("rt/chunk-2.json", jsonl(originals[2:]))

    service = run("in_gcs_basic.yaml", 4, server)
    service.stop()

    records = service.records()
    assert len(records) == 4
    for original, record in zip(originals, records):
        expected = {k: v for k, v in original.items() if k != "date"}
        expected["event_time"] = original["date"]
        assert record == expected
    # microsecond precision survives the trip
    assert [r["event_time"] for r in records] == [o["date"] for o in originals]
    assert records[3]["event_time"].endswith(".999993Z")


def run_to_exit(server, timeout=30):
    """Run with exit_on_complete and return (service, exit code)."""
    service = GcsService("in_gcs_exit.yaml", server, wait_for_ready=False)
    service.start()
    try:
        code = service.wait_for_exit(timeout)
    except BaseException:
        service.stop()
        raise
    return service, code


def test_in_gcs_exit_code_success():
    server = FakeGcsServer()
    sources, _ = make_records("ok", 2)
    server.add_object("exit/a.log", jsonl(sources))

    service, code = run_to_exit(server)
    service.wait_for_records(2)
    log = service.log()
    service.stop()

    assert code == 0
    assert "rehydration completed: objects processed=1 skipped=0 failed=0" in log


def test_in_gcs_exit_code_listing_forbidden():
    server = FakeGcsServer()
    sources, _ = make_records("never", 1)
    server.add_object("exit/a.log", jsonl(sources))
    server.fail_listing(100, status=403)

    service, code = run_to_exit(server)
    log = service.log()
    service.stop()

    assert code != 0
    assert "rehydration failed" in log
    assert service.records() == []
    assert server.object_requests() == []


def test_in_gcs_exit_code_failed_object():
    server = FakeGcsServer()
    for name in ("exit/a.log", "exit/b.log", "exit/c.log"):
        sources, _ = make_records(name, 1)
        server.add_object(name, jsonl(sources))
    server.fail_object("exit/b.log", 1000, status=500)

    service, code = run_to_exit(server)
    service.wait_for_records(2)
    log = service.log()
    service.stop()

    assert code == 1
    # the other objects were ingested; the failure is reported in the summary
    assert sorted(r["msg"] for r in service.records()) == ["exit/a.log-0", "exit/c.log-0"]
    assert "objects processed=2 skipped=0 failed=1" in log
    assert "rehydration completed with errors" in log
